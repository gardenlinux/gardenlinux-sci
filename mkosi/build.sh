#!/usr/bin/env bash
# Build mkosi systemd-sysext images: no argument builds all, <image> builds one.
# Usage: bash mkosi/build.sh [--bootstrap] [<image>]   (e.g. sci-10-base)
# --bootstrap stops after the toolchain (sandbox, tools tree, base tree): the
# consumer of the raws artifact prepares everything mkosi needs without
# rebuilding the extensions it receives as artifacts.
# Contract: docs/sysext-virt.md (build, tools tree, base image).

set -Eeuo pipefail

SCRIPT_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)
REPO_ROOT=$(cd -- "$SCRIPT_DIR/.." && pwd -P)
MKOSI_DIR=$REPO_ROOT/.build/mkosi
CONFIG_DIR=$SCRIPT_DIR
VENV_MKOSI=$MKOSI_DIR/venv/bin/mkosi
SANDBOX_DIR=$MKOSI_DIR/sandbox
TOOLS_DIR=$MKOSI_DIR/tools
TOOLS_TREE=$TOOLS_DIR/mkosi.tools
TOOLS_PIN_DISTRIBUTION=ubuntu
TOOLS_PIN_RELEASE=noble
TOOLS_PIN=$TOOLS_PIN_DISTRIBUTION/$TOOLS_PIN_RELEASE
TOOLS_PIN_FILE=$TOOLS_DIR/pin
TOOLS_CONTENT_PIN_FILE=$CONFIG_DIR/tools.pin
KEYRING=$REPO_ROOT/keyring.gpg

die() {
    printf 'error: %s\n' "$*" >&2
    exit 2
}

if [ "$#" -gt 1 ]; then
    die "usage: $0 [--bootstrap] [<image>]   (no argument builds every image; e.g. sci-10-base)"
fi
BOOTSTRAP_ONLY=0
IMAGE=${1:-}
if [ "$IMAGE" = "--bootstrap" ]; then
    BOOTSTRAP_ONLY=1
    IMAGE=
fi

if [ ! -x "$VENV_MKOSI" ]; then
    cat >&2 <<EOF
error: mkosi venv not found at $MKOSI_DIR/venv
Create it first (mkosi is not on PyPI; the host has no ensurepip, hence uv):

  uv venv "$MKOSI_DIR/venv"
  uv pip install --python "$MKOSI_DIR/venv/bin/python" "mkosi @ git+https://github.com/systemd/mkosi.git@v27.1"
EOF
    exit 2
fi

if [ -n "$IMAGE" ]; then
    [ -f "$CONFIG_DIR/mkosi.images/$IMAGE/mkosi.conf" ] \
        || die "unknown image '$IMAGE' (no $CONFIG_DIR/mkosi.images/$IMAGE/mkosi.conf)"
fi
[ -f "$KEYRING" ] || die "missing keyring $KEYRING"

# The suite version and its timestamp come from Release= in mkosi.conf.
RELEASE_COUNT=$(grep -c '^Release=' -- "$CONFIG_DIR/mkosi.conf") || true
[ "$RELEASE_COUNT" -le 1 ] \
    || die "$CONFIG_DIR/mkosi.conf contains $RELEASE_COUNT Release= lines; expected exactly one (the suite version source of truth)"
SUITE=$(sed -n 's/^Release=//p' -- "$CONFIG_DIR/mkosi.conf" | head -n 1)
[ -n "$SUITE" ] || die "no Release= in $CONFIG_DIR/mkosi.conf (the suite version source of truth)"
GARDEN_VERSION=$REPO_ROOT/bin/garden-version
if [ ! -x "$GARDEN_VERSION" ]; then
    die "missing $GARDEN_VERSION (it is a symlink into the gardenlinux submodule; check it out with 'git submodule update --init gardenlinux')"
fi
EPOCH=$("$GARDEN_VERSION" --epoch "$SUITE") \
    || die "cannot derive the build epoch: '$GARDEN_VERSION --epoch $SUITE' failed"
[[ $EPOCH =~ ^[0-9]+$ ]] \
    || die "'$GARDEN_VERSION --epoch $SUITE' did not return an integer timestamp: '$EPOCH'"

# keyring.gpg is a symlink; cp -L dereferences it.
rm -rf -- "$SANDBOX_DIR"
mkdir -p -- "$SANDBOX_DIR"
cp -a -- "$CONFIG_DIR/sandbox/." "$SANDBOX_DIR/"
mkdir -p -- "$SANDBOX_DIR/usr/share/keyrings"
cp -L -- "$KEYRING" "$SANDBOX_DIR/usr/share/keyrings/gardenlinux.gpg"

# The assembled sandbox apt source must name the same suite as Release=.
SANDBOX_SOURCES=$SANDBOX_DIR/etc/apt/sources.list.d/mkosi.sources
[ -f "$SANDBOX_SOURCES" ] \
    || die "missing $SANDBOX_SOURCES in the assembled sandbox (expected the Garden Linux apt source)"
SOURCES_SUITE=$(sed -n 's/^Suites:[[:space:]]*//p' -- "$SANDBOX_SOURCES" | head -n 1)
if [ "$SOURCES_SUITE" != "$SUITE" ]; then
    die "suite version skew: mkosi.conf sets Release=$SUITE but $SANDBOX_SOURCES sets Suites: ${SOURCES_SUITE:-<none>}"
fi

if [ -d "$TOOLS_TREE" ] \
    && [ "$(cat "$TOOLS_PIN_FILE" 2>/dev/null || true)" = "$TOOLS_PIN" ]; then
    :
else
    rm -rf -- "$TOOLS_TREE" "$TOOLS_PIN_FILE" "$TOOLS_DIR/mkosi.tools.manifest"
    mkdir -p -- "$TOOLS_DIR"
    cat >"$TOOLS_DIR/mkosi.conf" <<EOF
# Generated by mkosi/build.sh. Builds only mkosi's default tools tree.
# Distribution=custom + Format=none keeps the main image empty; the tools tree
# itself is $TOOLS_PIN, whose tooling the host lacks (erofs-utils,
# systemd-repart, ...).
[Distribution]
Distribution=custom

[Build]
ToolsTree=default
ToolsTreeDistribution=$TOOLS_PIN_DISTRIBUTION
ToolsTreeRelease=$TOOLS_PIN_RELEASE

[Output]
Format=none
EOF
    (
        cd -- "$TOOLS_DIR"
        "$VENV_MKOSI" build
    )
    [ -f "$TOOLS_CONTENT_PIN_FILE" ] \
        || die "missing $TOOLS_CONTENT_PIN_FILE (the committed sha256 of the tools-tree manifest; the fresh tree cannot be accepted without it)"
    TOOLS_CONTENT_PIN_COUNT=$(grep -cvE '^[[:space:]]*(#|$)' -- "$TOOLS_CONTENT_PIN_FILE") || TOOLS_CONTENT_PIN_COUNT=0
    [ "$TOOLS_CONTENT_PIN_COUNT" -eq 1 ] \
        || die "$TOOLS_CONTENT_PIN_FILE carries $TOOLS_CONTENT_PIN_COUNT digest lines; expected exactly one sha256 of the tools-tree manifest"
    TOOLS_CONTENT_PIN=$(grep -vE '^[[:space:]]*(#|$)' -- "$TOOLS_CONTENT_PIN_FILE" | head -n 1)
    TOOLS_CONTENT_PIN=${TOOLS_CONTENT_PIN//[[:space:]]/}
    [[ $TOOLS_CONTENT_PIN =~ ^[0-9a-f]{64}$ ]] \
        || die "$TOOLS_CONTENT_PIN_FILE digest is not a 64-hex-digit sha256: '$TOOLS_CONTENT_PIN'"
    TOOLS_MANIFEST=$TOOLS_DIR/mkosi.tools.manifest
    [ -f "$TOOLS_MANIFEST" ] \
        || die "the tools-tree bootstrap did not produce $TOOLS_MANIFEST; cannot verify the fresh tree against $TOOLS_CONTENT_PIN_FILE"
    TOOLS_MANIFEST_SHA256=$(sha256sum -- "$TOOLS_MANIFEST" | awk '{print $1}')
    [ "$TOOLS_MANIFEST_SHA256" = "$TOOLS_CONTENT_PIN" ] \
        || die "tools tree content drifted from the committed pin: $TOOLS_MANIFEST is $TOOLS_MANIFEST_SHA256 but $TOOLS_CONTENT_PIN_FILE pins $TOOLS_CONTENT_PIN; accepting the new toolchain requires updating $TOOLS_CONTENT_PIN_FILE in the same commit (the tree is not marked reusable)"
    printf '%s\n' "$TOOLS_PIN" >"$TOOLS_PIN_FILE"
fi

# Prepare the published base tree before any mkosi invocation.
BASE_IMAGE_TOOL=$CONFIG_DIR/base-image.sh
[ -f "$BASE_IMAGE_TOOL" ] \
    || die "missing $BASE_IMAGE_TOOL (the tool that prepares the published base tree from mkosi/base-image.pin)"
BASE_IMAGE_TREE=$(bash "$BASE_IMAGE_TOOL" ensure) \
    || die "cannot prepare the published base tree (bash $BASE_IMAGE_TOOL ensure failed)"
{ [ -n "$BASE_IMAGE_TREE" ] && [ -d "$BASE_IMAGE_TREE" ]; } \
    || die "base-image.sh ensure did not report a usable base tree ('$BASE_IMAGE_TREE')"

mkdir -p -- "$MKOSI_DIR/output"

if [ "$BOOTSTRAP_ONLY" -eq 1 ]; then
    printf 'mkosi/build.sh: toolchain ready (sandbox, tools tree, base tree); no images built\n'
    exit 0
fi

# Run from the config directory so paths in mkosi.conf resolve against it.
cd -- "$CONFIG_DIR"
if [ -n "$IMAGE" ]; then
    exec "$VENV_MKOSI" --source-date-epoch="$EPOCH" --dependency "$IMAGE" build
fi
exec "$VENV_MKOSI" --source-date-epoch="$EPOCH" build
